
// Лабораторная работа 3. Сортировка одномерных массивов.
// Варианты сортировок: "мини-макс", "пузырёк", "быстрая сортировка",
// сортировка чётных/нечётных значений, сортировка на интервале индексов.
#include <iostream>
#include <cstdlib>
#include <ctime>
#include <iomanip>
#include <cstring>
using namespace std;

const int N = 12;               // размер массива

// ---------------------------------------------------------------------
// 1. Сортировка методом "мини-макс" (из методических указаний).
// На каждом шаге k ищется минимальный элемент в неотсортированной части
// массива (от k до конца) и меняется местами с элементом b[k].
// ---------------------------------------------------------------------
void sort_minmax(int b[], int n)
{
    int i, k, m, ib, tmp;
    for (k = 0; k < n - 1; k++)        // позиция, в которую вставляется минимум
    {
        m = b[k];                      // m - текущий минимум, ib - его индекс
        ib = k;
        for (i = k + 1; i < n; i++)    // поиск минимума в "хвосте" массива
            if (m > b[i])
            {
                m = b[i];              // запоминаем новый минимум
                ib = i;                // и его позицию
            }
        // обмен найденного минимума с элементом b[k]:
        b[ib] = b[k]; b[k] = m;
    }
}

// ---------------------------------------------------------------------
// 2. Сортировка методом "пузырька".
// Соседние элементы сравниваются попарно; больший "всплывает" вверх.
// Флаг flag прерывает работу, если за проход не было ни одного обмена
// (массив уже отсортирован).
// ---------------------------------------------------------------------
void sort_bubble(int b[], int n)
{
    int i, j, tmp, flag;
    for (i = 0; i < n - 1; i++)        // число проходов по массиву
    {
        flag = 0;                      // признак "обменов не было"
        for (j = 0; j < n - 1 - i; j++)// сравнение соседних пар
            if (b[j] > b[j + 1])
            {
                tmp = b[j];            // обмен соседних элементов
                b[j] = b[j + 1];
                b[j + 1] = tmp;
                flag = 1;              // был обмен - сортировка не завершена
            }
        if (!flag) break;              // обменов нет -> массив отсортирован
    }
}

// ---------------------------------------------------------------------
// 3. Быстрая сортировка (qsort, Хоара).
// Выбирается опорный элемент (средний), массив делится на часть с
// элементами меньше опорного и часть с элементами больше опорного,
// затем обе части рекурсивно сортируются.
// ---------------------------------------------------------------------
void qsort_arr(int b[], int left, int right)
{
    int i = left, j = right, tmp;
    int x = b[(left + right) / 2];     // опорный элемент
    do
    {
        while (b[i] < x) i++;          // пропускаем элементы слева, меньшие x
        while (b[j] > x) j--;          // пропускаем элементы справа, большие x
        if (i <= j)                    // нашли "неправильную" пару - меняем
        {
            tmp = b[i]; b[i] = b[j]; b[j] = tmp;
            i++; j--;
        }
    } while (i <= j);
    if (left < j)  qsort_arr(b, left, j);   // сортировка левой части
    if (i < right) qsort_arr(b, i, right);  // сортировка правой части
}

// ---------------------------------------------------------------------
// 4. Сортировка по возрастанию чётных значений и по убыванию нечётных.
// Массив разбивается на чётные и нечётные значения; чётные сортируются
// по возрастанию, нечётные - по убыванию; значения возвращаются на те
// позиции, где стояли чётные/нечётные элементы соответственно.
// Вспомогательная функция: сортировка части массива по убыванию.
// ---------------------------------------------------------------------
void sort_desc_part(int b[], int n)
{
    int i, j, tmp;
    for (i = 0; i < n - 1; i++)
        for (j = 0; j < n - 1 - i; j++)
            if (b[j] < b[j + 1])
            {
                tmp = b[j]; b[j] = b[j + 1]; b[j + 1] = tmp;
            }
}

void sort_parity(int b[], int n)
{
    int i, j, tmp, ke = 0, ko = 0, evens[N], odds[N], ne, no;
    // разделяем значения на чётные и нечётные
    for (i = 0; i < n; i++)
        if (b[i] % 2 == 0) evens[ke++] = b[i];
        else               odds[ko++]  = b[i];
    ne = ke; no = ko;
    // чётные - по возрастанию, нечётные - по убыванию
    for (i = 0; i < ne - 1; i++)
        for (j = 0; j < ne - 1 - i; j++)
            if (evens[j] > evens[j + 1])
            { tmp = evens[j]; evens[j] = evens[j+1]; evens[j+1] = tmp; }
    sort_desc_part(odds, no);
    // возвращаем значения на свои места
    ke = ko = 0;
    for (i = 0; i < n; i++)
        if (b[i] % 2 == 0) b[i] = evens[ke++];
        else               b[i] = odds[ko++];
}

// ---------------------------------------------------------------------
// 5. Сортировка массива по возрастанию на интервале индексов [n1, n2].
// Реализована как обобщённая версия "мини-макса" с границами интервала.
// ---------------------------------------------------------------------
void sort_interval_asc(int b[], int n1, int n2)
{
    int i, k, m, ib;
    for (k = n1; k < n2; k++)          // границы интервала вместо границ массива
    {
        m = b[k]; ib = k;
        for (i = k + 1; i <= n2; i++)
            if (m > b[i])
            {
                m = b[i]; ib = i;
            }
        b[ib] = b[k]; b[k] = m;
    }
}

// 6. Сортировка массива по убыванию на интервале индексов [n1, n2].
void sort_interval_desc(int b[], int n1, int n2)
{
    int i, k, m, ib;
    for (k = n1; k < n2; k++)
    {
        m = b[k]; ib = k;
        for (i = k + 1; i <= n2; i++)
            if (m < b[i])              // знак сравнения изменён
            {
                m = b[i]; ib = i;
            }
        b[ib] = b[k]; b[k] = m;
    }
}

// Вывод массива на экран
void print_arr(const char *title, int b[], int n)
{
    cout << title;
    for (int i = 0; i < n; i++) cout << setw(6) << b[i];
    cout << endl;
}

int main()
{
    int a[N];
    srand((unsigned)time(0));
    for (int i = 0; i < N; i++) a[i] = rand() % 100;

    cout << "Исходный массив:" << endl;
    print_arr("  ", a, N);

    // проверка каждой сортировки на копии массива
    int b[N];

    memcpy(b, a, sizeof(a)); sort_minmax(b, N);
    print_arr("Мини-макс (по возрастанию):        ", b, N);

    memcpy(b, a, sizeof(a)); sort_bubble(b, N);
    print_arr("Пузырёк (по возрастанию):          ", b, N);

    memcpy(b, a, sizeof(a)); qsort_arr(b, 0, N - 1);
    print_arr("Быстрая сортировка (по возрастанию):", b, N);

    memcpy(b, a, sizeof(a)); sort_parity(b, N);
    print_arr("Чётные по возр., нечётные по убыв.:", b, N);

    memcpy(b, a, sizeof(a)); sort_interval_asc(b, 3, 8);
    print_arr("Интервал [3..8] по возрастанию:    ", b, N);

    memcpy(b, a, sizeof(a)); sort_interval_desc(b, 3, 8);
    print_arr("Интервал [3..8] по убыванию:       ", b, N);

    return 0;
}
